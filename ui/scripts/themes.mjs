//: **Themes** (ADR-0171): writes src/styles/themes.css, one
//: `:root[data-theme="<id>"]` block per theme, from today's tokens
//: (styles/tokens.css and styles/palette.css) by the design's rule
//: (lib/themeRule.js). Then checks it against the design: every name the
//: design's token sets share with ours, at today's value in both, must come
//: out as design/themes/tokens-<id>.css has it; and the theme values in
//: themeRule.js must be design/source/28/themes.js's.
//:
//:     node scripts/themes.mjs           write, then check
//:     node scripts/themes.mjs --check   check that the file is current too
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, recolour, corner, tone } from '../src/lib/themeRule.js';

const ui = join(dirname(fileURLToPath(import.meta.url)), '..');
const design = join(ui, '..', 'design');
const OUT = join(ui, 'src/styles/themes.css');

const decls = (text) => {
  const out = new Map();
  for (const m of text.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    if (!out.has(m[1])) out.set(m[1], m[2].trim());
  }
  return out;
};
const norm = (v) => v.replace(/\s+/g, '').toLowerCase();

const today = new Map([
  ...decls(readFileSync(join(ui, 'src/styles/tokens.css'), 'utf8')),
  ...decls(readFileSync(join(ui, 'src/styles/palette.css'), 'utf8')),
]);
const VEILS = new Set(['--cover-veil', '--cover-veil-strong', '--cover-veil-deep', '--remote-veil']);

function themed(name, value, T) {
  if (VEILS.has(name)) {
    //: ADR-0171 (5): every veil at the larger of today's alphas and the
    //: theme's - the theme's own, in all five.
    const b = recolour('#101a21', T).replace('#', '');
    const rgb = [0, 2, 4].map((i) => parseInt(b.slice(i, i + 2), 16)).join(',');
    return `radial-gradient(130% 105% at 20% 42%,rgba(${rgb},${T.veil[0]}),rgba(${rgb},${T.veil[1]}))`;
  }
  if (name === '--weave-angle') return `${T.weaveAngle}deg`;
  if (name === '--font-mono') return value.replace("'IBM Plex Mono'", T.mono);
  const r = /^(--r-[\w-]+|--[\w-]*radius[\w-]*)$/.test(name) && /^(\d+(?:\.\d+)?)px$/.exec(value);
  if (r) return `${corner(+r[1], T)}px`;
  if (/^\d{1,3},\s*\d{1,3},\s*\d{1,3}$/.test(value)) return tone(value, T).replace(/,/g, ', ');
  value = value.replace(/repeating-linear-gradient\(38deg,(\s*#3f5a6d)/g, `repeating-linear-gradient(${T.weaveAngle}deg,$1`);
  return recolour(value, T);
}

const blocks = [
  '/* Generated by ui/scripts/themes.mjs from styles/tokens.css and styles/palette.css',
  '   by the design\'s rule (lib/themeRule.js, ADR-0171). Do not edit: change a token',
  '   and run `node scripts/themes.mjs`. */',
];
for (const T of THEMES) {
  const lines = [];
  for (const [name, value] of today) {
    const v = themed(name, value, T);
    if (norm(v) !== norm(value)) lines.push(`  ${name}: ${v};`);
  }
  if (T.light) lines.push('  color-scheme: light;');
  blocks.push('', `:root[data-theme="${T.id}"] {`, ...lines, '}');
}
//: **What keeps today's look in every theme** (ADR-0171): an element marked
//: `theme-keep` - the idle screen, over its photograph - gets back today's
//: value of every token a theme changes, the mono included.
const changed = new Set();
for (const T of THEMES) for (const [name, value] of today) if (norm(themed(name, value, T)) !== norm(value)) changed.add(name);
blocks.push('', ':root[data-theme] .theme-keep {', ...[...changed].map((n) => `  ${n}: ${today.get(n)};`), '  color-scheme: dark;', '}');
const css = blocks.join('\n') + '\n';

let failed = 0;
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== css) {
    console.error('themes.css is not current: run node scripts/themes.mjs');
    failed++;
  }
} else {
  writeFileSync(OUT, css);
}

// The design's own values.
const designThemes = (() => {
  const js = readFileSync(join(design, 'source/28/themes.js'), 'utf8');
  return JSON.parse(js.slice(js.indexOf('['), js.lastIndexOf(']') + 1));
})();
for (const T of THEMES) {
  const D = designThemes.find((d) => d.id === T.id);
  for (const [k, v] of Object.entries(T)) {
    if (JSON.stringify(D?.[k]) !== JSON.stringify(v)) {
      console.error(`${T.id}.${k}: ${JSON.stringify(v)} here, ${JSON.stringify(D?.[k])} in design/source/28/themes.js`);
      failed++;
    }
  }
}
const designToday = decls(readFileSync(join(design, 'tokens.css'), 'utf8'));
let compared = 0, ours = 0;
for (const T of THEMES) {
  const theirs = decls(readFileSync(join(design, `themes/tokens-${T.id}.css`), 'utf8'));
  for (const [name, value] of today) {
    if (!theirs.has(name)) continue;
    const veil = name === '--cover-veil';
    if (!veil && (!designToday.has(name) || norm(designToday.get(name)) !== norm(value))) {
      ours++;
      if (process.argv.includes('--list') && T === THEMES[0]) console.log(`  apart today: ${name}: ${value}`);
      continue;
    }
    compared++;
    const mine = themed(name, value, T);
    if (norm(mine) !== norm(theirs.get(name))) {
      console.error(`${T.id} ${name}: ${mine} here, ${theirs.get(name)} in the design`);
      failed++;
    }
  }
}
//: **Phase 31's tokens** (design/source/31/tokens-radio-31.css): every colour
//: the rule gives must be the design's, the two picked accents with them. Its
//: corners are left out: that file kept them unscaled, while its artboards
//: scale them as the rule does (Bauhaus's row logo 10 px, Gauge's 6).
{
  const radio = readFileSync(join(design, 'source/31/tokens-radio-31.css'), 'utf8');
  const blocksOf = {};
  for (const b of radio.matchAll(/:root(?:\[data-theme="(\w+)"\])?\s*\{([^}]*)\}/g)) blocksOf[b[1] || 'default'] = decls(b[2]);
  for (const T of THEMES) {
    for (const [name, value] of blocksOf.default) {
      if (/radius/.test(name) || !blocksOf[T.id]?.has(name)) continue;
      compared++;
      const mine = themed(name, today.get(name) ?? value, T);
      if (norm(mine) !== norm(blocksOf[T.id].get(name))) {
        console.error(`${T.id} ${name}: ${mine} here, ${blocksOf[T.id].get(name)} in design/source/31`);
        failed++;
      }
    }
  }
}
console.log(`themes: ${THEMES.length} written; ${compared} values the same as the design's, ` +
  `${ours} names production sets apart today (left to the rule)`);
process.exit(failed ? 1 : 0);
